import sys
import os
import traceback
import subprocess
import json
import datetime

def run_git_log():
    try:
        repo_dir = os.path.dirname(os.path.abspath(__file__))
        res = subprocess.run(
            ['git', 'log', '-n', '10', '--pretty=format:%h - %an, %ar : %s'],
            cwd=repo_dir,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True
        )
        return res.stdout.strip()
    except Exception as e:
        return f"Git log unavailable: {str(e)}"

def main():
    workspace = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
    output_dir = os.path.join(workspace, 'TOAI_Generated')
    os.makedirs(output_dir, exist_ok=True)
    
    git_history = run_git_log()
    timestamp = datetime.datetime.now().isoformat()
    
    summary_data = {
        "timestamp": timestamp,
        "version": "1.0.0",
        "git_recent_commits": git_history,
        "description": "Release summary generated by build_release_summary.py for Gaia Ecosystem."
    }
    
    out_file = os.path.join(output_dir, 'release_summary.json')
    with open(out_file, 'w', encoding='utf-8') as f:
        json.dump(summary_data, f, ensure_ascii=False, indent=2)
    
    print(f"Release summary successfully built and saved to {out_file}")

if __name__ == '__main__':
    try:
        main()
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)
