import sys
import os
import traceback
import time
import json
import subprocess
from datetime import datetime

def get_git_log(repo_path, max_count=20):
    try:
        cmd = ['git', '-C', repo_path, 'log', f'-n {max_count}', '--pretty=format:%h - %an: %s (%ad)']
        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
        return result.stdout.splitlines()
    except Exception as e:
        return [f"Git log retrieval failed: {str(e)}"]

def main():
    try:
        workspace_dir = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
        repo_path = os.path.join(workspace_dir, 'TOAI-elegant-lang')
        
        if not os.path.exists(os.path.join(repo_path, '.git')):
            print("Git repository not found. Initializing repository for release tracking...")
            subprocess.run(['git', 'init', repo_path], check=True)
            subprocess.run(['git', '-C', repo_path, 'config', 'user.name', 'TOAI Release Agent'], check=True)
            subprocess.run(['git', '-C', repo_path, 'config', 'user.email', 'agent@toai.ecosystem'], check=True)
            # Create an initial commit if none exists
            dummy_file = os.path.join(repo_path, 'README.md')
            if not os.path.exists(dummy_file):
                with open(dummy_file, 'w', encoding='utf-8') as f:
                    f.write('# TOAI Elegant Lang\n')
            subprocess.run(['git', '-C', repo_path, 'add', '.'], check=True)
            subprocess.run(['git', '-C', repo_path, 'commit', '-m', 'Initial commit by TOAI release agent'], check=True)

        logs = get_git_log(repo_path)
        
        summary = {
            "timestamp": datetime.now().isoformat(),
            "version": "1.0.0",
            "release_notes": "Automated release summary generated by TOAI ecosystem agent.",
            "recent_commits": logs
        }
        
        output_dir = os.path.join(workspace_dir, 'TOAI_Generated')
        os.makedirs(output_dir, exist_ok=True)
        output_path = os.path.join(output_dir, 'release_summary.json')
        
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(summary, f, ensure_ascii=False, indent=2)
            
        print(f"Successfully generated release summary at: {output_path}")
        
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)

if __name__ == '__main__':
    main()
