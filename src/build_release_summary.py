import sys
import os
import traceback
import time
import json
import subprocess
from datetime import datetime

def run_git_command(args, cwd):
    try:
        result = subprocess.run(
            ["git"] + args,
            cwd=cwd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True
        )
        return result.stdout.strip()
    except Exception as e:
        print(f"Git command failed: {e}")
        return ""

def main():
    workspace_dir = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
    repo_dir = os.path.join(workspace_dir, 'TOAI-elegant-lang')
    
    if not os.path.exists(repo_dir):
        print(f"Repository directory not found: {repo_dir}")
        sys.exit(1)
        
    os.chdir(repo_dir)
    
    # Check if git repo exists
    if not os.path.exists(os.path.join(repo_dir, '.git')):
        print("Not a git repository. Initializing...")
        subprocess.run(["git", "init"], check=True)
        subprocess.run(["git", "config", "user.name", "TOAI Release Bot"], check=True)
        subprocess.run(["git", "config", "user.email", "bot@toai.internal"], check=True)
        subprocess.run(["git", "add", "."], check=True)
        subprocess.run(["git", "commit", "--allow-empty", "-m", "Initial commit"], check=True)

    git_log = run_git_command(["log", "-n", "10", "--pretty=format:%h - %an, %ar : %s"], repo_dir)
    latest_tag = run_git_command(["describe", "--tags", "--abbrev=0"], repo_dir)
    if not latest_tag:
        latest_tag = "v0.1.0-alpha"
        
    summary_data = {
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "version": latest_tag,
        "recent_commits": git_log.splitlines() if git_log else [],
        "description": "Automated release summary generated by TOAI-elegant-lang build system."
    }
    
    output_path = os.path.join(repo_dir, 'release_summary.json')
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(summary_data, f, indent=2, ensure_ascii=False)
        
    print(f"Release summary successfully generated at: {output_path}")

if __name__ == '__main__':
    try:
        main()
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)
