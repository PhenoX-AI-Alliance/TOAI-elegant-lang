import sys
import os
import traceback
import subprocess
import json
import datetime

def get_git_logs():
    try:
        cmd = ["git", "log", "-n", "10", "--oneline"]
        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
        return result.stdout.strip().splitlines()
    except Exception as e:
        print(f"Warning: Could not fetch git logs: {e}")
        return []

def main():
    try:
        workspace_dir = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
        target_dir = os.path.join(workspace_dir, 'TOAI-elegant-lang', 'src')
        os.makedirs(target_dir, exist_ok=True)
        
        logs = get_git_logs()
        
        summary = {
            "timestamp": datetime.datetime.now().isoformat(),
            "version": "1.0.0",
            "recent_commits": logs,
            "description": "Release summary generated by TOAI automated pipeline."
        }
        
        output_file = os.path.join(target_dir, 'release_summary.json')
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(summary, f, ensure_ascii=False, indent=2)
            
        print(f"Successfully generated release summary at: {output_file}")
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)

if __name__ == '__main__':
    main()
