import sys
import os
import traceback
import subprocess
import json
from datetime import datetime

def get_git_log(repo_path, max_count=20):
    try:
        cmd = ['git', '-C', repo_path, 'log', f'-n', str(max_count), '--pretty=format:%h - %an: %s (%ad)']
        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
        return result.stdout.splitlines()
    except Exception as e:
        print(f"Warning: Failed to fetch git log: {e}")
        return []

def main():
    try:
        workspace_dir = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
        repo_path = os.path.join(workspace_dir, 'TOAI-elegant-lang')
        
        if not os.path.exists(os.path.join(repo_path, '.git')):
            print("Notice: Git repository not initialized. Initializing for release logging...")
            subprocess.run(['git', 'init', repo_path], capture_output=True, text=True)
            subprocess.run(['git', '-C', repo_path, 'config', 'user.name', 'TOAI Executor'], capture_output=True, text=True)
            subprocess.run(['git', '-C', repo_path, 'config', 'user.email', 'executor@toai.internal'], capture_output=True, text=True)
            # Make an initial commit if none exists
            subprocess.run(['git', '-C', repo_path, 'add', '.'], capture_output=True, text=True)
            subprocess.run(['git', '-C', repo_path, 'commit', '-m', 'Initial commit for release summary'], capture_output=True, text=True)

        logs = get_git_log(repo_path)
        
        summary_data = {
            "timestamp": datetime.utcnow().isoformat(),
            "version": "1.0.0",
            "git_logs": logs,
            "description": "Release summary generated by TOAI ecosystem builder."
        }
        
        output_dir = os.path.join(workspace_dir, 'TOAI_Generated')
        os.makedirs(output_dir, exist_ok=True)
        output_file = os.path.join(output_dir, 'release_summary.json')
        
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(summary_data, f, indent=2, ensure_ascii=False)
            
        print(f"Successfully generated release summary at: {output_file}")
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)

if __name__ == '__main__':
    main()
