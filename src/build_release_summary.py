import os
import sys
import subprocess
import json
import datetime
import traceback

def get_git_log():
    try:
        if not os.path.exists('.git'):
            return "Git repository not initialized."
        result = subprocess.run(
            ['git', 'log', '-n', '10', '--oneline'],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True
        )
        return result.stdout.strip()
    except Exception as e:
        return f"Failed to retrieve git log: {e}"

def scan_whitepaper():
    candidates = ['WHITE_PAPER.md', 'README.md', 'CONSTITUTION.md']
    summary_data = {}
    for c in candidates:
        if os.path.exists(c):
            try:
                with open(c, 'r', encoding='utf-8') as f:
                    content = f.read()
                    summary_data[c] = content[:300] + ('...' if len(content) > 300 else '')
            except Exception as e:
                summary_data[c] = f"Error reading file: {e}"
    return summary_data

def generate_summary():
    git_logs = get_git_log()
    whitepaper_info = scan_whitepaper()
    
    release_report = {
        "timestamp": datetime.datetime.now().isoformat(),
        "version": "1.0.0-gaia",
        "git_recent_commits": git_logs.splitlines(),
        "whitepaper_snippets": whitepaper_info,
        "message": "Generated by TOAI Release Summary Builder with altruistic intent."
    }
    
    output_file = 'release_summary.json'
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(release_report, f, indent=2, ensure_ascii=False)
    
    print(f"Successfully generated release summary at {output_file}")

if __name__ == '__main__':
    try:
        generate_summary()
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)
