import sys
import os
import traceback
import time
import json
import subprocess
from datetime import datetime

def main():
    try:
        workspace_dir = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
        repo_path = os.path.join(workspace_dir, 'TOAI-elegant-lang')
        
        git_log = "No git repository found or git command failed."
        if os.path.exists(os.path.join(repo_path, '.git')):
            try:
                result = subprocess.run(
                    ['git', '-C', repo_path, 'log', '-n', '10', '--pretty=format:%h - %an, %ad : %s'],
                    capture_output=True,
                    text=True,
                    check=True
                )
                git_log = result.stdout
            except Exception as e:
                git_log = f"Failed to fetch git log: {str(e)}"
        
        summary_data = {
            "timestamp": datetime.now().isoformat(),
            "version": "1.0.0",
            "git_recent_commits": git_log.splitlines(),
            "description": "Release summary generated by TOAI automated pipeline with altruistic value delivery."
        }
        
        output_dir = os.path.join(workspace_dir, 'TOAI_Generated')
        os.makedirs(output_dir, exist_ok=True)
        
        output_file = os.path.join(output_dir, 'release_summary.json')
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(summary_data, f, indent=2, ensure_ascii=False)
            
        print(f"Successfully generated release summary at: {output_file}")
        
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)

if __name__ == '__main__':
    main()
