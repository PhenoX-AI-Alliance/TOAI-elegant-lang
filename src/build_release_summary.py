import sys
import os
import traceback
import time
import json
import subprocess
from datetime import datetime

def run_git_command(args, cwd):
    try:
        result = subprocess.run(
            ["git"] + args,
            cwd=cwd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True
        )
        return result.stdout.strip()
    except Exception as e:
        return f"Error executing git command: {e}"

def main():
    workspace = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
    repo_path = os.path.join(workspace, 'TOAI-elegant-lang')
    
    if not os.path.exists(os.path.join(repo_path, '.git')):
        print("Git repository not found. Initializing...")
        try:
            subprocess.run(["git", "init"], cwd=repo_path, check=True)
            subprocess.run(["git", "config", "user.name", "TOAI Release Agent"], cwd=repo_path, check=True)
            subprocess.run(["git", "config", "user.email", "agent@toai.local"], cwd=repo_path, check=True)
        except Exception as e:
            print(f"Failed to initialize git: {e}")
            sys.exit(1)
            
    git_log = run_git_command(["log", "-n", "10", "--oneline"], repo_path)
    git_status = run_git_command(["status", "--short"], repo_path)
    
    summary_data = {
        "timestamp": datetime.now().isoformat(),
        "git_log": git_log,
        "git_status": git_status,
        "release_notes": "Automated release summary generated by TOAI ecosystem."
    }
    
    output_path = os.path.join(workspace, 'TOAI_Generated', 'release_summary.json')
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(summary_data, f, ensure_ascii=False, indent=2)
        
    print(f"Release summary successfully written to {output_path}")

if __name__ == '__main__':
    try:
        main()
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)
