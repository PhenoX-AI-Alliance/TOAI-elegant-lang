#!/usr/bin/env python3
import sys
import os
import traceback
import time
import json
import subprocess
import datetime

def get_git_log(max_count=10):
    try:
        result = subprocess.run(
            ['git', 'log', f'-n {max_count}', '--pretty=format:%h - %an: %s (%ad)'],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True
        )
        return result.stdout.strip()
    except Exception as e:
        return f"Git log retrieval failed: {str(e)}"

def scan_whitepaper():
    workspace = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
    potential_paths = [
        os.path.join(workspace, 'WHITE_PAPER.md'),
        os.path.join(workspace, 'TOAI-elegant-lang', 'WHITE_PAPER.md'),
        os.path.join(workspace, 'CONSTITUTION.md')
    ]
    summary = []
    for path in potential_paths:
        if os.path.exists(path):
            try:
                with open(path, 'r', encoding='utf-8') as f:
                    content = f.read(1000)
                    summary.append(f"--- File: {os.path.basename(path)} ---\n{content[:300]}...")
            except Exception as ex:
                summary.append(f"Error reading {path}: {str(ex)}")
    return "\n".join(summary) if summary else "No whitepaper or constitution found."

def main():
    try:
        workspace = os.environ.get('TOAI_WORKSPACE_DIR', '/home/phenox/gemini-sandbox/')
        output_dir = os.path.join(workspace, 'TOAI_Generated')
        os.makedirs(output_dir, exist_ok=True)
        
        git_history = get_git_log(15)
        whitepaper_info = scan_whitepaper()
        
        now = datetime.datetime.now().isoformat()
        
        release_data = {
            "timestamp": now,
            "git_log": git_history,
            "whitepaper_summary": whitepaper_info,
            "status": "success",
            "message": "Release summary successfully generated by TOAI executor."
        }
        
        out_file = os.path.join(output_dir, 'release_summary.json')
        with open(out_file, 'w', encoding='utf-8') as f:
            json.dump(release_data, f, ensure_ascii=False, indent=2)
            
        print(f"Release summary successfully built at: {out_file}")
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)

if __name__ == '__main__':
    main()
