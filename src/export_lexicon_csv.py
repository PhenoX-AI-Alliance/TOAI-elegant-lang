import sys
import os
import traceback
import time
import json
import csv

def main():
    sandbox_dir = '/home/phenox/gemini-sandbox'
    lexicon_json_path = os.path.join(sandbox_dir, 'TOAI-elegant-lang', 'src', 'core_lexicon.json')
    output_csv_path = os.path.join(sandbox_dir, 'TOAI-elegant-lang', 'src', 'core_lexicon.csv')
    
    try:
        if not os.path.exists(lexicon_json_path):
            default_data = {
                "metadata": {
                    "version": "1.0.0",
                    "description": "TOAI Core Lexicon"
                },
                "entries": [
                    {
                        "term": "Gaia",
                        "category": "ecosystem",
                        "definition": "The living earth system embodying altruism, warmth, and abundance."
                    },
                    {
                        "term": "AltruisticMonetization",
                        "category": "economy",
                        "definition": "Sustainable economic cycles generated by providing genuine value."
                    }
                ]
            }
            os.makedirs(os.path.dirname(lexicon_json_path), exist_ok=True)
            with open(lexicon_json_path, 'w', encoding='utf-8') as f:
                json.dump(default_data, f, indent=2, ensure_ascii=False)
        
        with open(lexicon_json_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
            
        entries = data.get('entries', [])
        
        os.makedirs(os.path.dirname(output_csv_path), exist_ok=True)
        with open(output_csv_path, 'w', encoding='utf-8', newline='') as csvfile:
            fieldnames = ['term', 'category', 'definition']
            writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
            
            writer.writeheader()
            for entry in entries:
                writer.writerow({
                    'term': entry.get('term', ''),
                    'category': entry.get('category', ''),
                    'definition': entry.get('definition', '')
                })
                
        print(f"Successfully exported lexicon to {output_csv_path}")
        
    except Exception as e:
        traceback.print_exc()
        sys.exit(1)

if __name__ == '__main__':
    main()
